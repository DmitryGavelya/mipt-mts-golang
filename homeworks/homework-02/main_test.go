package main

import "testing"

type gameCase struct {
	step    int
	command string
	answer  string
}

func runCases(t *testing.T, cases []gameCase) {
	initGame()
	for _, c := range cases {
		got := handleCommand(c.command)
		if got != c.answer {
			t.Errorf("step %d\n\tcmd:  %s\n\tgot:  %q\n\twant: %q", c.step, c.command, got, c.answer)
		}
	}
}

func TestHappyPathClearsWave(t *testing.T) {
	runCases(t, []gameCase{
		{1, "атаковать", "Урон противнику: 10. Противник повержен."},
		{2, "дальше", "Следующий противник: skeleton, HP 10/10."},
		{3, "атаковать", "Урон противнику: 10. Скелет восстаёт с HP 5. Урон вам: 2. Ваше HP: 18/20."},
		{4, "атаковать", "Урон противнику: 10. Противник повержен."},
		{5, "дальше", "Следующий противник: goblin, HP 15/15."},
		{6, "атаковать", "Урон противнику: 10. HP противника: 5/15. Урон вам: 4. Ваше HP: 14/20."},
		{7, "атаковать", "Урон противнику: 10. Противник повержен."},
		{8, "дальше", "Волна пройдена. Победа! Ваше HP: 14/20."},
	})
}

